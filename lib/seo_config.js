export function getBrandSeo(brandStr) {
    if (!brandStr) return null;
    const key = Object.keys(seoConfig).find(k => k.toLowerCase() === brandStr.toLowerCase());
    return key ? seoConfig[key].meta : null;
}

export function getModelSeo(brandStr, modelStr) {
    if (!brandStr || !modelStr) return null;
    const brandKey = Object.keys(seoConfig).find(k => k.toLowerCase() === brandStr.toLowerCase());
    if (brandKey && seoConfig[brandKey].models) {
        const modelKey = Object.keys(seoConfig[brandKey].models).find(k => k.toLowerCase() === modelStr.toLowerCase());
        return modelKey ? seoConfig[brandKey].models[modelKey] : null;
    }
    return null;
}

export function formatTitleCase(str) {
    if (!str) return '';
    return str.split(/[\s-]+/).map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}
