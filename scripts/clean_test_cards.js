/**
 * Команда для запуска скрипта в терминале сервера:
 * node scripts/clean_test_cards.js
 */

import { PrismaClient } from '@prisma/client';
const prisma = new PrismaClient();

async function main() {
  // Выводим огромное предупреждение красным цветом (используем ANSI-коды для цвета)
  console.log('\x1b[31m%s\x1b[0m', '======================================================================');
  console.log('\x1b[31m%s\x1b[0m', 'ВНИМАНИЕ! Вы собираетесь удалить ВСЕ сгенерированные карточки ошибок');
  console.log('\x1b[31m%s\x1b[0m', 'из базы данных! (таблица DiagnosticReport)');
  console.log('\x1b[31m%s\x1b[0m', '======================================================================');
  
  // Сообщаем пользователю о возможности отменить операцию желтым цветом
  console.log('\x1b[33m%s\x1b[0m', 'Удаление начнется через 10 секунд. Нажмите Ctrl+C для отмены.');

  // Делаем паузу в 10 секунд (10000 миллисекунд), используя Promise и setTimeout
  await new Promise(resolve => setTimeout(resolve, 10000));

  console.log('Ожидание завершено. Начинаем удаление данных...');

  try {
    // Выполняем удаление всех записей в таблице DiagnosticReport
    const deleteResult = await prisma.diagnosticReport.deleteMany({});
    
    // Выводим сообщение об успешном удалении зеленым цветом, показываем количество удаленных строк
    console.log('\x1b[32m%s\x1b[0m', `Успешно очищено! Удалено карточек: ${deleteResult.count}`);
  } catch (error) {
    // В случае ошибки выводим её в консоль
    console.error('\x1b[31m%s\x1b[0m', 'Произошла ошибка во время удаления данных:');
    console.error(error);
  } finally {
    // Обязательно закрываем соединение с базой данных после завершения всех операций
    await prisma.$disconnect();
    console.log('Соединение с базой данных закрыто.');
    // Завершаем процесс Node.js (0 означает успешное завершение)
    process.exit(0);
  }
}

// Запускаем основную функцию
main();
